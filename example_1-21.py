product_name = input()
price_per_kg = int(input())
weight = int(input())
user_money = int(input())
cost = int(price_per_kg) * int(weight)
change = int(user_money) - int(cost)
print(f"================Чек================")
print(f"Товар: {product_name:>29}")
print(f"Цена: {weight:>18}кг * {price_per_kg}руб/кг")
print(f"Итого: {cost:>26}руб")
print(f"Внесено: {user_money:>24}руб")
print(f"Сдача: {change:>26}руб")
print("===================================")